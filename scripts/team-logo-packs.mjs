export function teamDifficulty(index) {
  return index < 10 ? 'easy' : index < 23 ? 'medium' : 'hard';
}

export function sameDivisionDistractors(teams, slug, division, prefix) {
  return teams
    .filter(([candidateSlug, , , , candidateDivision]) => candidateSlug !== slug && candidateDivision === division)
    .map(([candidateSlug]) => `${prefix}-${candidateSlug}`);
}
